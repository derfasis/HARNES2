import path from 'node:path';
import Ajv from 'ajv';
import { ROOT, readJson } from './config.mjs';
import { scoutAssessmentDiagnostic } from './scout-assessment-output.mjs';
import { digest } from './source-ingestion.mjs';
export const SCOUT_QUERY_CONTRACT=readJson(path.join(ROOT,'contracts/scout-query-intent.schema.json'));
const validate=new Ajv({strict:true}).compile(SCOUT_QUERY_CONTRACT);
export function scoutQueryOutput(result,packet){
 const reject=(reason,code='SCOUT_EVIDENCE_INVALID',stage='evidence',extra={})=>({output:null,reason,diagnostic:scoutAssessmentDiagnostic({code,stage,...extra,...(code==='SCOUT_MODEL_INCOMPLETE'?{failure_cause:result?.failure_cause}:{})})});
 if(result?.completed!==true||result.error)return reject('SCOUT_QUERY_MODEL_INCOMPLETE','SCOUT_MODEL_INCOMPLETE','model');
 if(result.tool_calls!=null&&(!Array.isArray(result.tool_calls)||result.tool_calls.length)
   ||result.messages!=null&&(!Array.isArray(result.messages)||result.messages.some(m=>m?.role==='tool'
     ||m?.tool_calls!=null&&(!Array.isArray(m.tool_calls)||m.tool_calls.length)||m?.function_call!=null)))return reject('SCOUT_QUERY_TOOLS_FORBIDDEN','SCOUT_TOOLS_FORBIDDEN','envelope');
 if(typeof result.final_response!=='string')return reject('SCOUT_QUERY_OUTPUT_INVALID','SCOUT_OUTPUT_NOT_TEXT','format');
 if(Buffer.byteLength(result.final_response)>32000)return reject('SCOUT_QUERY_OUTPUT_INVALID','SCOUT_OUTPUT_TOO_LARGE','format');
 let output;try{output=JSON.parse(result.final_response);}catch{return reject('SCOUT_QUERY_OUTPUT_INVALID',/^\s*```/.test(result.final_response)?'SCOUT_JSON_MARKDOWN_FENCE':'SCOUT_JSON_INVALID','format');}
 if(!validate(output))return reject('SCOUT_QUERY_SCHEMA_INVALID','SCOUT_SCHEMA_INVALID','schema',{schema_keywords:validate.errors.map(e=>e.keyword)});
 const seen=new Set();
 for(const item of output.items){
   const message=packet.messages.find(m=>m.message_id===item.message_id);
   if(!message||seen.has(item.message_id))return reject('SCOUT_QUERY_EVIDENCE_INVALID');
   // Unknown/cross-source ancestry cannot become attributed business intent.
   if(item.classification==='own_business_request'&&(!message.author_ref||message.missing_parent||message.reply_to_source&&message.reply_to_source!==packet.source_ref))return reject('SCOUT_QUERY_ATTRIBUTION_UNPROVEN');
   if(message.missing_parent&&item.missing_context.length===0)return reject('SCOUT_QUERY_CONTEXT_UNPROVEN');
   seen.add(item.message_id);
 }
 // Literal source truth is projected by code, never generated by a model.
 return {output:{...output,items:output.items.map(item=>({...item,quoted_text:packet.messages.find(m=>m.message_id===item.message_id).text}))},reason:null,diagnostic:null};
}
export function scoutQueryStoredOutput(output,packet){
 if(!output||!Array.isArray(output.items))return null;
 const raw={...output,items:output.items.map(item=>{const {quoted_text,...model}=item??{};return model;})};
 const checked=scoutQueryOutput({completed:true,final_response:JSON.stringify(raw)},packet);
 return checked.output&&digest(checked.output)===digest(output)?checked.output:null;
}
